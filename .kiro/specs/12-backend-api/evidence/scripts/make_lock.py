"""Spec 12 T5 (OD-124): regenerate cji_agent/requirements.lock with the two new test-group packages.

1. Copy the current lock to evidence/requirements.lock.before.
2. Constraints = every pin of the current lock, so nothing already locked can move.
3. uv pip compile pyproject.toml --group dev --universal --python-version 3.12 --generate-hashes -c constraints.
4. evidence/lock-diff.txt: added, removed and changed pins. Anything other than additions makes the script exit 1.

Usage:  python make_lock.py <uv executable>
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
SPEC = HERE.parents[2]
APP = SPEC.parents[2] / "cji_agent"
EVIDENCE = SPEC / "evidence"
CONSTRAINTS = EVIDENCE / "lock-constraints.txt"
BEFORE = EVIDENCE / "requirements.lock.before"
LOCK = APP / "requirements.lock"
DIFF = EVIDENCE / "lock-diff.txt"
HEADER = (
    "# Exact tested dependency set for cji-agent (runtime + dev groups), with hashes. Spec 11, OD-101; Spec 12, OD-124.\n"
    "# Generated by .kiro/specs/12-backend-api/evidence/scripts/make_lock.py "
    "(uv pip compile pyproject.toml --group dev --universal --python-version 3.12 --generate-hashes,\n"
    "# constrained to the previous lock's versions). Install: pip install -r requirements.lock\n"
)


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_lock(path: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith((" ", "\t", "#")) or not line.strip():
            continue
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)", line)
        if m:
            pins[canonical(m.group(1))] = m.group(2)
    return pins


def main() -> int:
    uv = sys.argv[1]
    if not BEFORE.exists():
        shutil.copy2(LOCK, BEFORE)
    before = read_lock(BEFORE)
    CONSTRAINTS.write_text("# Generated by make_lock.py (Spec 12): every pin of the previous lock\n"
                           + "".join(f"{n}=={v}\n" for n, v in sorted(before.items())),
                           encoding="utf-8", newline="\n")
    cmd = [uv, "pip", "compile", "pyproject.toml", "--group", "dev", "--universal", "--python-version", "3.12",
           "--generate-hashes", "-c", "../" + CONSTRAINTS.relative_to(APP.parent).as_posix(),
           "-o", "requirements.lock", "--no-header", "--index-url", "https://pypi.org/simple"]
    print(" ".join(cmd))
    proc = subprocess.run(cmd, cwd=APP, capture_output=True, text=True, check=False)
    print(proc.stdout[-4000:])
    print(proc.stderr[-6000:], file=sys.stderr)
    if proc.returncode != 0:
        return proc.returncode
    LOCK.write_text(HEADER + LOCK.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    lock = read_lock(LOCK)
    added = sorted(set(lock) - set(before))
    removed = sorted(set(before) - set(lock))
    changed = sorted(n for n in set(lock) & set(before) if lock[n] != before[n])
    lines = [
        f"lock: {len(lock)} packages (before: {len(before)})",
        f"\n== added ({len(added)})", *[f"  {n}=={lock[n]}" for n in added],
        f"\n== removed ({len(removed)})", *[f"  {n}=={before[n]}" for n in removed],
        f"\n== changed versions ({len(changed)})", *[f"  {n}: {before[n]} -> {lock[n]}" for n in changed],
    ]
    DIFF.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
    return 1 if removed or changed else 0


if __name__ == "__main__":
    raise SystemExit(main())
