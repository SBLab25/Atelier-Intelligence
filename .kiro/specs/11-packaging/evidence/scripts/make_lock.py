"""Spec 11 T3 (design §5, OD-101): build cji_agent/requirements.lock constrained to the tested versions.

1. Constraints = baseline venv freeze (evidence/survey/baseline-freeze.txt) minus the packages OD-100 removes and
   minus filelock (security floor); plus, for packages the baseline does not have (pip-audit and its
   dependencies), the versions from the scratch venv the survey ran pip-audit in.
2. uv pip compile pyproject.toml --group dev --universal --python-version 3.12 --generate-hashes -c constraints.
3. evidence/lock-diff.txt: removed, added and changed versions against the baseline freeze. A changed version
   other than filelock is unexpected and makes the script exit 1.

Usage:  python make_lock.py <uv executable> [scratch freeze]
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
SPEC = HERE.parents[2]
APP = SPEC.parents[2] / "cji_agent"
EVIDENCE = SPEC / "evidence"
BASELINE = EVIDENCE / "survey" / "baseline-freeze.txt"
CONSTRAINTS = EVIDENCE / "lock-constraints.txt"
LOCK = APP / "requirements.lock"
DIFF = EVIDENCE / "lock-diff.txt"

REMOVED = {"litellm", "anthropic", "langchain-community", "sentence-transformers", "pytest-asyncio", "pytest-cov"}
EXPECTED_CHANGES = {"filelock"}


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_freeze(path: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line.strip())
        if m:
            pins[canonical(m.group(1))] = m.group(2)
    return pins


def read_lock(path: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith((" ", "\t", "#")) or not line.strip():
            continue
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)", line)
        if m:
            pins[canonical(m.group(1))] = m.group(2)
    return pins


def main() -> int:
    uv = sys.argv[1]
    scratch = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    baseline = read_freeze(BASELINE)
    constraints = {n: v for n, v in baseline.items() if n not in REMOVED and n != "filelock"}
    extra = {}
    if scratch and scratch.exists():
        extra = {n: v for n, v in read_freeze(scratch).items() if n not in baseline and n not in REMOVED}
        constraints.update(extra)
    CONSTRAINTS.write_text(
        "# Generated by make_lock.py: baseline venv versions (minus OD-100 removals and filelock)"
        + (f"; {len(extra)} from the scratch venv\n" if extra else "\n")
        + "".join(f"{n}=={v}\n" for n, v in sorted(constraints.items())),
        encoding="utf-8", newline="\n",
    )
    cmd = [uv, "pip", "compile", "pyproject.toml", "--group", "dev", "--universal", "--python-version", "3.12",
           "--generate-hashes", "-c", "../" + CONSTRAINTS.relative_to(APP.parent).as_posix(),   # relative: no local path in the lock "-o", "requirements.lock", "--no-header",
           "--index-url", "https://pypi.org/simple"]
    print(" ".join(cmd))
    proc = subprocess.run(cmd, cwd=APP, capture_output=True, text=True, check=False)
    print(proc.stdout[-4000:])
    print(proc.stderr[-6000:], file=sys.stderr)
    if proc.returncode != 0:
        return proc.returncode
    body = LOCK.read_text(encoding="utf-8")
    header = ("# Exact tested dependency set for cji-agent (runtime + dev groups), with hashes. Spec 11, OD-101.\n"
              "# Generated by .kiro/specs/11-packaging/evidence/scripts/make_lock.py "
              "(uv pip compile pyproject.toml --group dev --universal --python-version 3.12 --generate-hashes,\n"
              "# constrained to the versions the test suite ran with). Install: pip install -r requirements.lock\n")
    LOCK.write_text(header + body, encoding="utf-8", newline="\n")

    lock = read_lock(LOCK)
    removed = sorted(set(baseline) - set(lock))
    added = sorted(set(lock) - set(baseline))
    changed = sorted(n for n in set(lock) & set(baseline) if lock[n] != baseline[n])
    unexpected = [n for n in changed if n not in EXPECTED_CHANGES]
    lines = [
        f"lock: {len(lock)} packages; baseline venv: {len(baseline)} distributions",
        f"\n== removed from the environment ({len(removed)})",
        *[f"  {n}=={baseline[n]}" for n in removed],
        f"\n== added ({len(added)}): pip-audit and its dependencies, platform-specific packages for other systems",
        *[f"  {n}=={lock[n]}" for n in added],
        f"\n== changed versions ({len(changed)}); expected only: {sorted(EXPECTED_CHANGES)}",
        *[f"  {n}: {baseline[n]} -> {lock[n]}" for n in changed],
        f"\n== unexpected version changes: {len(unexpected)}",
        *[f"  {n}" for n in unexpected],
    ]
    DIFF.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines[:1] + [f"removed={len(removed)} added={len(added)} changed={len(changed)} "
                                 f"unexpected={unexpected}"]))
    return 1 if unexpected else 0


if __name__ == "__main__":
    raise SystemExit(main())
